-- Execute no SQL Editor do Supabase para habilitar o histórico remoto.
create table if not exists public.community_simulations (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text not null default 'Simulação da comunidade',
  scenario text not null default 'custom',
  payload jsonb not null
);

alter table public.community_simulations enable row level security;

-- Política inicial para ambiente de demonstração: acesso público de leitura/inserção.
-- NÃO use esta política em produção com dados pessoais ou confidenciais.
create policy "demo_read_simulations"
  on public.community_simulations for select
  to anon, authenticated using (true);
create policy "demo_insert_simulations"
  on public.community_simulations for insert
  to anon, authenticated with check (true);

